test("catalog has explicit executable or inapplicable checks for both registries", async () => {
  const cases = await json("bench/cases.json"),
    ledger = await json("bench/checklist.json");
  assert.equal(new Set(cases.map((c) => c.id)).size, cases.length);
  assert.equal(ledger.length, 84);
  for (const side of ["legacy", "migrated"]) {
    const registry = await json(".generated/" + side + ".json");
    const parser = createParser(registry.schema, registry.root);
    assert.deepEqual(
      ledger.map((l) => l.component).sort(),
      Object.keys(registry.components).sort(),
    );
    for (const c of cases) {
      validateCase(c);
      if (!c.setup.directHorizontal && !c.setup.sharedSession) {
        const p = parser.parse(c.source);
        assert.deepEqual(p.meta.errors, [], c.id);
        assert.deepEqual(p.meta.unresolved, [], c.id);
      }
    }
  }
  for (const entry of ledger)
    for (const check of entry.checks) {
      if (!check.applicable) {
        assert(check.reason);
        continue;
      }
      assert(check.cases.length, check.id);
      assert(check.assertions.length, check.id);
      for (const id of check.cases) {
        const c = cases.find((c) => c.id === id);
        assert(c, check.id);
        const assertions = [
          ...c.assertions,
          ...(c.streamingAssertions ?? []),
          ...c.steps.flatMap((s) => s.assertions ?? []),
        ].map((a) => a.id);
        assert(
          check.assertions.some((id) => assertions.includes(id)),
          check.id,
        );
      }
    }
  for (const name of ["Label", "Slice", "SwitchGroup", "SwitchItem"])
    assert(
      cases
        .filter((c) => c.coverage.includes(name) && c.id.includes("default"))
        .every((c) => !c.deliveries.includes("stream")),
    );
});
test("theme definitions have supported public fields and independently reproducible hashes", () => {
  const keys = new Set([
    ...Object.keys(defaultLightTheme),
    ...CHART_PALETTE_KEYS,
  ]);
  assert.deepEqual(
    themePresetFixture.presets.map((p) => p.id),
    ["default", "cyberpunk", "crimson-desert"],
  );
  for (const p of themePresetFixture.presets) {
    assert.equal(
      hash(
        JSON.stringify({
          version: themePresetFixture.version,
          id: p.id,
          label: p.label,
          lightTheme: p.lightTheme,
          darkTheme: p.darkTheme,
        }),
      ),
      p.definitionHash,
    );
    for (const mode of ["lightTheme", "darkTheme"])
      for (const key of Object.keys(p[mode])) assert(keys.has(key), key);
  }
});
test("host CSS is genuinely generated by pinned Tailwind versions with preflight retained", async () => {
  const manifest = await json("public/bench-host/manifest.json");
  for (const [name, version] of [
    ["tailwind3", "3.4.17"],
    ["tailwind4", "4.1.18"],
  ]) {
    const css = await fs.readFile("public/bench-host/" + name + ".css", "utf8");
    assert.equal(hash(css), manifest.files[name].sha256);
    assert(css.includes("tailwindcss v" + version));
    assert(css.includes("box-sizing"));
    assert(css.includes("bg-red-500"));
  }
  assert.equal(
    (await json("node_modules/tailwindcss3/package.json")).version,
    "3.4.17",
  );
  assert.equal(
    (await json("node_modules/@tailwindcss/postcss/package.json")).version,
    "4.1.18",
  );
});
test("public bootstrap/case APIs expose no server key, enforce origin and do not invent assertions", async () => {
  const secret = "synthetic-bench-test-key-not-a-real-credential";
  const app = await createApp({
    env: {
      NODE_ENV: "production",
      COMPARISON_MODE: "live",
      THESYS_API_KEY: secret,
      THESYS_BASE_URL: "http://127.0.0.1:1/v1",
      THESYS_MODEL: "not-contacted",
    },
  });
  app.server.listen(0, "127.0.0.1");
  await once(app.server, "listening");
  let savedId;
  const origin = `http://127.0.0.1:${app.server.address().port}`;
  try {
    const html = await (await fetch(origin + "/?mode=offline")).text();
    assert(html.includes("comparison-config"));
    assert(!html.includes(secret));
    const forbidden = await fetch(origin + "/bench-api/cases", {
      method: "POST",
      headers: {
        Origin: "http://wrong.test",
        "Content-Type": "application/json",
      },
      body: "{}",
    });
    assert.equal(forbidden.status, 403);
    const response = await fetch(origin + "/bench-api/cases", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        name: "Explicit saved negative input",
        source: 'root = Card([TextContent("<script>not executable</script>")])',
        coverage: [],
        assertions: [],
        steps: [],
      }),
    });
    assert.equal(response.status, 201);
    const result = await response.json();
    savedId = result.case.id;
    assert.deepEqual(result.case.assertions, []);
    assert.match(result.status, /Not covered/);
    assert(!JSON.stringify(result).includes(secret));
    assert.equal(
      (
        await fetch(origin + "/bench-api/runs/" + savedId + "/cancel", {
          method: "POST",
          body: "{}",
        })
      ).status,
      400,
    );
  } finally {
    if (savedId) await fs.unlink(".bench-cases/" + savedId + ".json");
    await app.close();
  }
});

test("Slider invalid-value fixture follows the installed optional-min validation contract", async () => {
  const rules = parseStructuredRules({ min: 40 });
  assert.equal(
    validate(undefined, rules),
    undefined,
    "optional unset values are valid",
  );
  assert.equal(builtInValidators.min([10], 40), "Must be at least 40");
  assert.equal(validate([10], rules), "Must be at least 40");
  assert.equal(validate([50], rules), undefined);
  const cases = await json("bench/cases.json");
  const invalid = cases.find((c) => c.id === "slider-validation-error");
  assert.equal(invalid.steps[0].op, "key");
  assert.equal(invalid.steps[0].key, "ArrowRight");
  assert.equal(invalid.steps[1].op, "click");
});

