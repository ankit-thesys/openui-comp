// Generate the server entry while retaining value references for consumer bundlers.
import { library } from "#paths";
import { readdirSync, writeFileSync } from "node:fs";
import { format, resolveConfig } from "prettier";

const entry = library("src/styles.ts");
const modules = readdirSync(library("src"), { recursive: true, encoding: "utf8" })
  .filter((file) => file.endsWith(".styles.ts"))
  .map((file) => `./${file.replace(/\.ts$/, "")}`)
  .sort();
const source = `// Generated by styles:entry. Do not edit by hand.
// The full component sheet without rendering anything. Importable from a React Server Component.
${modules.map((module, index) => `import * as s${index} from "${module}";`).join("\n")}
import { getComponentStyles as collect, type ConfigureStylesOptions } from "./styles/css";

// Referenced so bundlers keep the imports: style modules are side-effect free in package.json.
const modules = [${modules.map((_, index) => `s${index}`).join(", ")}];

/** Every component rule, for <style data-openui-styles> in <head>. */
export const getComponentStyles = (options?: ConfigureStylesOptions): string =>
  modules.length ? collect(options) : " ";

export { ComponentStyles, type ComponentStylesProps } from "./ComponentStyles";
export type { ConfigureStylesOptions };
`;
writeFileSync(entry, await format(source, { ...(await resolveConfig(entry)), filepath: entry }));
