import * as core from "@openuidev/react-ui-core";
import assert from "node:assert/strict";
import test from "node:test";

test("core exposes extracted controls through the public root", () => {
  for (const name of [
    "Button",
    "Input",
    "TextArea",
    "Buttons",
    "IconButton",
    "Label",
    "FormControl",
    "Hint",
    "CheckBoxGroup",
    "CheckBoxItem",
    "RadioGroup",
    "RadioItem",
    "SwitchGroup",
    "SwitchItem",
    "ToggleGroup",
    "ToggleItem",
    "Calendar",
    "DatePicker",
    "Select",
    "SelectTrigger",
    "SelectContent",
    "SelectGroup",
    "SelectLabel",
    "SelectItem",
    "SelectSeparator",
    "SelectValue",
    "Slider",
    "SliderBlock",
    "Chips",
    "OptionCards",
    "LayoutContext",
    "LayoutContextProvider",
    "useLayoutContext",
    "Card",
    "CardHeader",
    "Separator",
    "FoldableSectionRoot",
    "FoldableSectionItem",
    "FoldableSectionTrigger",
    "FoldableSectionContent",
    "SectionV2",
    "Skeleton",
    "TableSkeleton",
    "PieChartSkeleton",
    "DotMatrixLoader",
    "Accordion",
    "AccordionItem",
    "AccordionTrigger",
    "AccordionContent",
    "Carousel",
    "CarouselContent",
    "CarouselItem",
    "CarouselPrevious",
    "CarouselNext",
    "Steps",
    "StepsItem",
    "Tabs",
    "TabsList",
    "TabsTrigger",
    "TabsContent",
  ])
    assert(core[name], `Missing root component: ${name}`);
  assert.equal("FormControlProvider" in core, false);
  assert.equal("useFormControlContext" in core, false);
});
