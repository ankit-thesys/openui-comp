#!/usr/bin/env node
// Experimental Next.js App Router installer: no CSS ordering decisions left to consumers.
import fs from 'node:fs/promises';
import path from 'node:path';
import {createRequire} from 'node:module';
import {parse} from '@babel/parser';
import {artifacts} from './generated-styles.js';
const root=path.resolve(process.argv[2]||'.');
const pkg=JSON.parse(await fs.readFile(path.join(root,'package.json'),'utf8'));
const deps={...pkg.dependencies,...pkg.devDependencies};
const require=createRequire(path.join(root,'package.json'));
const react=require('react/package.json').version;
if(Number(react.split('.')[0])!==19)throw Error('This prototype requires React 19.');
if(!deps.next)throw Error('Automatic ordered CSS integration currently supports Next.js App Router only.');
let framework='none',version=null,mode='unlayered';
if(deps.tailwindcss){version=require('tailwindcss/package.json').version;const major=Number(version.split('.')[0]);if(![3,4].includes(major))throw Error('Unsupported Tailwind major: '+major);framework='tailwind'+major;if(major===4)mode='layered';}
else if(deps.bootstrap){framework='bootstrap';version=require('bootstrap/package.json').version;}
const layouts=[];
for(const dir of ['app','src/app'])for(const ext of ['js','jsx','ts','tsx']){
 const candidate=path.join(root,dir,'layout.'+ext);try{await fs.access(candidate);layouts.push(candidate);}catch(e){if(e.code!=='ENOENT')throw e;}
}
if(layouts.length!==1)throw Error('Expected one conventional App Router root layout; no files changed.');
const layout=layouts[0];const source=await fs.readFile(layout,'utf8');
const ast=parse(source,{sourceType:'module',plugins:['jsx',...(layout.endsWith('.ts')||layout.endsWith('.tsx')?['typescript']:[])]});
const stylesheet='./openui.generated.css';
const imports=ast.program.body.filter(n=>n.type==='ImportDeclaration');
const existing=imports.find(n=>n.source.value===stylesheet);
if(existing&&imports[0]!==existing)throw Error('Generated stylesheet is no longer the first import. Review layout ordering; no files changed.');
const offset=ast.program.directives.at(-1)?.end??ast.program.interpreter?.end??0;
const layoutAfter=existing?source:source.slice(0,offset)+"\nimport './openui.generated.css'; // OpenUI: component defaults before app CSS\n"+source.slice(offset);
const entry=`'use client';\n// GENERATED by openui-prototype-configure. Framework: ${framework}; version: ${version}.\nimport {createComponents} from '@openui/goober-compat-prototype';\nexport const {Button}=createComponents('${mode}','external');\n`;
const bundle=artifacts[mode];
const css='/* GENERATED by openui-prototype-configure. Do not edit. */\n'+(mode==='layered'?'@layer theme,base,components,utilities;\n':'')+bundle.css+'\n'+bundle.late.css+'\n';
const generated=[[path.join(root,'openui.generated.js'),entry],[path.join(path.dirname(layout),'openui.generated.css'),css]];
// Validate the complete write set before touching either generated files or the user's layout.
for(const [file,content]of generated){try{if(await fs.readFile(file,'utf8')!==content)throw Error('Existing generated file differs: '+path.relative(root,file)+'. Review a diff before replacing it; no files changed.');}catch(e){if(e.code!=='ENOENT')throw e;}}
for(const [file,content]of generated)await fs.writeFile(file,content);
if(layoutAfter!==source)await fs.writeFile(layout,layoutAfter);
const report={framework,version,mode,react,delivery:'external build stylesheet',generated:generated.map(([file])=>path.relative(root,file)),layout:path.relative(root,layout),layoutImportFirst:true,consumerAction:'Run configure once, then import generated components. The tool adds the CSS import before app imports; no manual stylesheet or provider setup.',tradeoff:'All installed prototype styles, including delayed variants, are included in the initial stylesheet. Dynamic runtime CSS is not supported by this path.'};
await fs.writeFile(path.join(root,'openui-setup.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report));
