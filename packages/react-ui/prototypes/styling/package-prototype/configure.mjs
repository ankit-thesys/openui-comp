#!/usr/bin/env node
// Experimental installer: identifies installed direct dependencies, not browser heuristics.
import fs from 'node:fs/promises';
import path from 'node:path';
import {createRequire} from 'node:module';
const root=path.resolve(process.argv[2]||'.');
const pkg=JSON.parse(await fs.readFile(path.join(root,'package.json'),'utf8'));
const deps={...pkg.dependencies,...pkg.devDependencies};
const require=createRequire(path.join(root,'package.json'));
const react=require('react/package.json').version;
if(Number(react.split('.')[0])!==19)throw Error('This prototype requires React 19.');
let framework='none',version=null,mode='unlayered';
if(deps.tailwindcss){version=require('tailwindcss/package.json').version;const major=Number(version.split('.')[0]);if(![3,4].includes(major))throw Error('Unsupported Tailwind major: '+major);framework='tailwind'+major;if(major===4)mode='layered';}
else if(deps.bootstrap){framework='bootstrap';version=require('bootstrap/package.json').version;}
const output=path.join(root,'openui.generated.js');
const content=`'use client';\n// GENERATED by openui-prototype-configure. Framework: ${framework}; version: ${version}.\nimport {createComponents} from '@openui/goober-compat-prototype';\nexport const {Button}=createComponents('${mode}');\n`;
try{const old=await fs.readFile(output,'utf8');if(old!==content)throw Error('Existing generated entry differs. Review a diff before replacing it; no file was overwritten');}catch(e){if(e.code!=='ENOENT')throw e;}
await fs.writeFile(output,content);
const report={framework,version,mode,react,generated:['openui.generated.js'],consumerAction:'Run configure once, then import generated components. No manually selected CSS policy.'};
await fs.writeFile(path.join(root,'openui-setup.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report));
