// Library-only build process: compile/extract before shipping; no render-time Goober state.
import {css,keyframes,extractCss} from 'goober';
import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {rules,cssRule} from '../lib/styles.js';
const artifacts={};
for(const mode of ['unlayered','layered']){
 extractCss();
 const compile=css;
 const fade=keyframes({from:{opacity:0},to:{opacity:1}});
 const classes=Object.fromEntries(Object.entries(rules).map(([name,rule])=>{
  const style=cssRule(name==='bar'?{...rule,animation:fade+' 200ms ease-out'}:rule);
  const scoped={'&:where([data-openui-style])':style};
  return [name,compile(mode==='layered'?{'@layer components':scoped}:scoped)];
 }));
 const sheet=extractCss();
 // Separate resource used only by delayed/mounted content, to test streaming insertion.
 const lateRule={'&:where([data-openui-style])':{...cssRule(rules.button),backgroundColor:'var(--openui-late, #126c48)'}};
 const lateClass=css(mode==='layered'?{'@layer components':lateRule}:lateRule);
 const lateCSS=extractCss();
 artifacts[mode]={classes,css:sheet,href:'openui-prototype-'+createHash('sha256').update(sheet).digest('hex').slice(0,16),late:{className:lateClass,css:lateCSS,href:'openui-prototype-'+createHash('sha256').update(lateCSS).digest('hex').slice(0,16)}};
}
await fs.writeFile('lib/generated-styles.js','// GENERATED by scripts/generate-styles.mjs; do not edit.\nexport const artifacts='+JSON.stringify(artifacts,null,2)+';\n');
console.log('Generated package-owned Goober styles for package-owned browser and React 19 SSR delivery.');
