/**
 * Browser fixture for #31.
 *
 * One page, one scenario per `?s=<name>`, rendering the UNCHANGED legacy
 * components from packages/react-ui/src.
 *
 * Harness protocol, matching the sibling baseline fixtures:
 *   - `window.__ready === true` once a scenario has mounted.
 *   - `window.__probe` collects recorded values the runner asserts on.
 *   - `window.__error` is set if a scenario throws while rendering.
 *   - `#unknown-scenario` renders when `?s=` names nothing, so a typo fails
 *     loudly instead of silently reporting an empty pass.
 *
 * Every image source is a LOCAL asset generated by tools/make-assets.mjs. No
 * scenario references a remote URL, and the runner additionally blocks and
 * records non-local requests at the protocol level.
 */
