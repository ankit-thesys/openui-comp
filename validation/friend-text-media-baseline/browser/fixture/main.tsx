const name = new URLSearchParams(window.location.search).get("s") ?? "";
const factory = scenarios[name];

const App = () => {
  if (!factory) {
    record("unknownScenario", name);
    return (
      <pre id="unknown-scenario">
        unknown scenario: {JSON.stringify(name)}
        {"\n"}known: {Object.keys(scenarios).sort().join(", ")}
      </pre>
    );
  }
  return <>{factory()}</>;
};

window.addEventListener("error", (event) => {
  (window as unknown as { __error: string }).__error = event.message;
});

try {
  createRoot(document.getElementById("root")!).render(
    <StrictMode>
      <App />
    </StrictMode>,
  );
  // Flip ready only after a frame, so layout-dependent components (ScrollableTable
  // measures its container) have settled before the runner starts measuring.
  requestAnimationFrame(() => {
    requestAnimationFrame(() => {
      (window as unknown as { __ready: boolean }).__ready = true;
    });
  });
} catch (error) {
  (window as unknown as { __error: string }).__error =
    error instanceof Error ? error.message : String(error);
  (window as unknown as { __ready: boolean }).__ready = true;
}
